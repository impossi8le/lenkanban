-- Субъект автоматики для #20: ограниченные по действиям и сроку API-токены.
--
-- Изменения аддитивны и не меняют существующие строки:
--   * scopes     — пустой массив по умолчанию, то есть ранее выпущенные токены
--                  становятся read-only. Это осознанное ужесточение: запись
--                  через Bearer требует явного scope, а сессионный вход scopes
--                  не проверяет и работает как прежде.
--   * expiresAt  — NULL означает «бессрочный», что сохраняет поведение
--                  существующих токенов.
--
-- DEFAULT на массиве задан явно, чтобы уже вставленные строки получили
-- '{}' без отдельного UPDATE и без перезаписи данных.

ALTER TABLE "ApiToken" ADD COLUMN IF NOT EXISTS "scopes" TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[];
ALTER TABLE "ApiToken" ADD COLUMN IF NOT EXISTS "expiresAt" TIMESTAMP(3);
