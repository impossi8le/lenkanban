export interface TaskEvent {
  origin?: "automation";
  trigger: string;
  taskId: string;
  projectId: string;
  userId: string;
  /** Durable command identity, when supplied by the mutation result. */
  operationId?: string;
  oldValue?: unknown;
  newValue?: unknown;
  task?: unknown;
}
interface Condition {
  field: string;
  operator: string;
  value: unknown;
}
type AutomationTask = Prisma.TaskGetPayload<{
  include: { assignees: true; tags: { include: { tag: true } } };
}>;

export class AutomationExecutionError extends Error {
  constructor(readonly code: "INVALID_ACTIONS" | "INVALID_CONDITIONS" | "RECIPIENT_UNAVAILABLE" | "TASK_UNAVAILABLE") {
    super(code);
    this.name = "AutomationExecutionError";
  }
}
export class AutomationProcessingError extends Error {
  constructor(readonly failures: readonly Error[]) {
    super("Automation processing failed");
    this.name = "AutomationProcessingError";
  }
}

function report(event: "automation.rule.completed" | "automation.rule.failed" | "automation.process.failed",
  input: Pick<TaskEvent, "taskId" | "projectId">, ruleId?: string, error?: unknown): void {
  try {
    const errorCode = error instanceof AutomationExecutionError || error instanceof TaskCommandError
      ? error.code : "EXECUTION_FAILED";
    const fields = { event, taskId: input.taskId, projectId: input.projectId,
      ...(ruleId ? { ruleId } : {}), ...(error ? { errorCode } : {}) };
    if (event === "automation.rule.completed") automationLogger.info(fields);
    else automationLogger.error(fields);
  } catch { /* No raw fallback; diagnostics never change execution. */ }
}

function safeFailure(error: unknown): Error {
  try {
    if (error instanceof AutomationExecutionError) return new AutomationExecutionError(error.code);
    if (error instanceof TaskCommandError) return new TaskCommandError(error.code);
  } catch { /* Unknown thrown values are never inspected or stringified further. */ }
  return new Error("Automation execution failed");
}

function readConditions(value: unknown): Condition[] {
  if (!Array.isArray(value)) throw new AutomationExecutionError("INVALID_CONDITIONS");
  return value.map(row => {
    if (!row || typeof row !== "object" || typeof row.field !== "string" || typeof row.operator !== "string") {
      throw new AutomationExecutionError("INVALID_CONDITIONS");
    }
    return { field: row.field, operator: row.operator, value: row.value };
  });
}

/**
 * One rule, one transaction; caller task projections never authorize or supply content.
 *
 * All actions join this transaction through their shared mutation services.
 * Chaining is none: events generated by automation carry origin=automation.
 * Access remains bound to the current event actor; system execution grants no
 * additional rights. Receipts, Task, Activity and notifications commit together.
 * Realtime and generated event delivery happen only after commit.
 */
export async function processAutomationRules(input: TaskEvent): Promise<void> {
  if (input.origin === "automation") return;
  const invocationId = input.operationId ?? randomUUID();
  const event: TaskEvent = {
    trigger: input.trigger, taskId: input.taskId, projectId: input.projectId, userId: input.userId,
    oldValue: input.oldValue, newValue: input.newValue,
    operationId: input.operationId,
  };
  let rules: { id: string }[];
  try {
    rules = await prisma.automationRule.findMany({
      where: { projectId: event.projectId, active: true, trigger: event.trigger },
      select: { id: true },
    });
  } catch (error) {
    report("automation.process.failed", event, undefined, error);
    throw new AutomationProcessingError([new Error("Automation discovery failed")]);
  }
  const failures: Error[] = [];
  for (const candidate of rules) {
    try {
      const committed = await prisma.$transaction(async tx => {
        await prepareLegacyTaskScalarBatch({
          tx, actorId: event.userId, expectedTasks: [{ id: event.taskId, projectId: event.projectId }],
        });
        const rule = await tx.automationRule.findUnique({ where: { id: candidate.id } });
        if (!rule || !rule.active || rule.projectId !== event.projectId || rule.trigger !== event.trigger) return null;
        const actions = parseAutomationActions(rule.actions);
        if (!actions) throw new AutomationExecutionError("INVALID_ACTIONS");
        const task = await tx.task.findUnique({
          where: { id: event.taskId }, include: { assignees: true, tags: { include: { tag: true } } },
        });
        if (!task || task.id !== event.taskId || task.projectId !== event.projectId) {
          throw new AutomationExecutionError("TASK_UNAVAILABLE");
        }
        if (!evaluateConditions(readConditions(rule.conditions), task, event)) return null;
        let plan: AutomationNotificationPlan;
        try {
          plan = planAutomationNotifications(actions, task);
        } catch (error) {
          if (error instanceof AutomationNotificationPlanError) {
            throw new AutomationExecutionError(error.code);
          }
          throw error;
        }
        for (const userId of plan.recipients) {
          const recipient = await tx.user.findUnique({ where: { id: userId }, select: { id: true, globalRole: true } });
          if (!recipient || !(await getProjectAccess(recipient, task.projectId, tx)).canRead) {
            throw new AutomationExecutionError("RECIPIENT_UNAVAILABLE");
          }
        }
        const ruleKey = JSON.stringify(["automation-rule-v1", event.projectId, event.taskId, invocationId, candidate.id]);
        if (event.operationId || actions.some(action => action.type !== "notify_creator" && action.type !== "notify_assignees")) {
          // Reuse the existing unique receipt store without changing the move's
          // receipt/response. Moves accept UUIDs; this namespaced key cannot
          // collide with a move. ON CONFLICT waits for an overlapping claimant
          // and returns count=0 after its commit. A rollback releases the claim
          // together with the notifications, allowing a later retry.
          const claim = await tx.taskMoveOperation.createMany({
            data: [{
              operationId: ruleKey,
              taskId: event.taskId,
              projectId: event.projectId,
              requestHash: "automation-rule-v1",
              response: {},
            }],
            skipDuplicates: true,
          });
          if (claim.count !== 1) return null;
        }
        const notifications = await persistNotificationsWithClient(tx, plan.notifications);
        const effects = await executeAutomationMutations({ tx, actions, event, ruleKey });
        return { notifications, effects };
      }, { isolationLevel: Prisma.TransactionIsolationLevel.Serializable, maxWait: 5_000, timeout: 15_000 });
      if (committed !== null) {
        // These are exactly the rows returned by this committed rule transaction.
        try { deliverNotifications(committed.notifications); } catch { /* Commit survives delivery failures. */ }
        for (const move of committed.effects.moves) {
          try { await emitTaskMoved(event.projectId, move); } catch { /* Commit survives effects. */ }
        }
        if (committed.effects.updated) {
          try {
            const task = await loadTaskWithRelations(event.taskId);
            if (task?.project.id === event.projectId) await emitTaskUpdated(event.projectId, task);
          } catch { /* Commit survives effects. */ }
        }
        for (const generated of committed.effects.events) await processAutomationRules(generated);
        report("automation.rule.completed", event, candidate.id);
      }
    } catch (error) {
      report("automation.rule.failed", event, candidate.id, error);
      // Legacy callers may log the aggregate. Never carry storage messages or
      // raw rule/condition objects into that public failure surface.
      failures.push(safeFailure(error));
    }
  }
  if (failures.length > 0) throw new AutomationProcessingError(failures);
}

/** Facts every canonical move caller can provide after its transaction commits. */
export interface MoveAutomationInput {
  taskId: string;
  projectId: string;
  /** Event actor; the processor re-checks current access without a bypass. */
  userId: string;
  /**
   * Authoritative status read in the same request before `moveTask`.
   * This avoids unnecessary events on sequential retries; overlapping requests
   * are deduplicated transactionally using result.operationId, not this read.
   */
  previousStatus: string;
  result: { operationId?: string; task: { id: string; status: string } };
  /** Set only when the caller can prove the move was a stored replay. */
  replayed?: boolean;
}

function isIdentity(value: unknown): value is string {
  return typeof value === "string" && value.length > 0;
}

/**
 * Single builder for `status_changed` events. Move and PATCH must use the same
 * trigger/old/new shape so rule conditions behave identically on both paths.
 * Unchanged status (same-column reorder, same workflow key) yields no event.
 */
export function statusChangeAutomationEvent(input: {
  taskId: string;
  projectId: string;
  userId: string;
  previousStatus: string;
  nextStatus: string;
}): TaskEvent | null {
  if (!isIdentity(input.taskId) || !isIdentity(input.projectId) || !isIdentity(input.userId)
    || !isIdentity(input.previousStatus) || !isIdentity(input.nextStatus)) return null;
  if (input.previousStatus === input.nextStatus) return null;
  return {
    trigger: "status_changed",
    taskId: input.taskId,
    projectId: input.projectId,
    userId: input.userId,
    oldValue: input.previousStatus,
    newValue: input.nextStatus,
  };
}

/**
 * Event for a canonical move, or null when the move must stay silent:
 * same-column reorder, unchanged derived status, a stored operationId replay,
 * or a result that does not belong to the requested task.
 */
export function moveAutomationEvent(input: MoveAutomationInput): TaskEvent | null {
  if (input.replayed === true) return null;
  if (!isIdentity(input.taskId) || !isIdentity(input.projectId) || !isIdentity(input.userId)) return null;
  const result: unknown = input.result;
  if (!result || typeof result !== "object" || !("task" in result)) return null;
  const task: unknown = result.task;
  if (!task || typeof task !== "object" || !("id" in task) || !("status" in task)) return null;
  if (task.id !== input.taskId || typeof task.status !== "string") return null;
  const event = statusChangeAutomationEvent({
    taskId: input.taskId,
    projectId: input.projectId,
    userId: input.userId,
    previousStatus: input.previousStatus,
    nextStatus: task.status,
  });
  if (event && "operationId" in result && isIdentity(result.operationId)) {
    event.operationId = result.operationId;
  }
  return event;
}

/**
 * Bulk/bulk-update counterpart: one event per row whose derived status really
 * changed. Rows that kept their status (same-column or same workflow key) are
 * dropped, and a repeated taskId contributes at most one event.
 */
export function bulkMoveAutomationEvents(
  inputs: readonly MoveAutomationInput[],
): TaskEvent[] {
  const events: TaskEvent[] = [];
  const seen = new Set<string>();
  for (const input of inputs) {
    const event = moveAutomationEvent(input);
    if (event === null || seen.has(event.taskId)) continue;
    seen.add(event.taskId);
    events.push(event);
  }
  return events;
}

/**
 * Call only after the move transaction committed. A failed or rolled-back move
 * never reaches this function, so it cannot create side effects. Automation
 * failures do not change the committed move; callers may log them through the
 * existing automation logger.
 */
export async function processMoveAutomation(input: MoveAutomationInput): Promise<void> {
  const event = moveAutomationEvent(input);
  if (event === null) return;
  await processAutomationRules(event);
}

/**
 * Runs the committed bulk events in order. Every event is independent: one
 * failing rule set does not stop the remaining tasks, and the first failure is
 * rethrown at the end so the caller keeps its existing failure surface.
 */
export async function processBulkMoveAutomation(
  inputs: readonly MoveAutomationInput[],
): Promise<void> {
  let failure: unknown = null;
  for (const event of bulkMoveAutomationEvents(inputs)) {
    try {
      await processAutomationRules(event);
    } catch (error) {
      if (failure === null) failure = error;
    }
  }
  if (failure !== null) throw failure;
}

function evaluateConditions(conditions: Condition[], task: AutomationTask, event: TaskEvent): boolean {
  if (conditions.length === 0) return true;
  return conditions.every(condition =>
    evaluateCondition(getFieldValue(task, condition.field, event), condition.operator, condition.value));
}

function getFieldValue(task: AutomationTask, field: string, event: TaskEvent): unknown {
  switch (field) {
    case "status": return task.status;
    case "priority": return task.priority;
    case "assignee_count": return task.assignees?.length || 0;
    case "tag_count": return task.tags?.length || 0;
    case "has_deadline": return !!task.deadline;
    case "is_overdue": return task.deadline && new Date(task.deadline) < new Date();
    case "new_value": return event.newValue;
    case "old_value": return event.oldValue;
    default: return task[field as keyof AutomationTask];
  }
}

function evaluateCondition(fieldValue: unknown, operator: string, value: unknown): boolean {
  switch (operator) {
    case "equals": return fieldValue === value;
    case "not_equals": return fieldValue !== value;
    case "contains": return String(fieldValue).includes(String(value));
    case "not_contains": return !String(fieldValue).includes(String(value));
    case "greater_than": return Number(fieldValue) > Number(value);
    case "less_than": return Number(fieldValue) < Number(value);
    case "is_empty": return !fieldValue || fieldValue === "" || (Array.isArray(fieldValue) && fieldValue.length === 0);
    case "is_not_empty": return !!fieldValue && (Array.isArray(fieldValue) ? fieldValue.length > 0 : true);
    default: return false;
  }
}
